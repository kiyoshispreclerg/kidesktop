static int mkdirs(const char *path)
{
    char tmp[PATH_MAX];
    snprintf(tmp, sizeof(tmp), "%s", path);
    for (char *p = tmp + 1;; p++) {
        if (*p == '/' || !*p) {
            char c = *p;
            *p = '\0';
            if (mkdir(tmp, 0755) != 0 && errno != EEXIST) {
                fprintf(stderr, "kitheme-export: mkdir %s: %s\n", tmp, strerror(errno));
                return 0;
            }
            if (!c)
                return 1;
            *p = c;
        }
    }
}

static FILE *open_out(const char *dir, const char *rel, char *final, size_t fsz)
{
    char sub[PATH_MAX + 64];
    snprintf(final, fsz, "%s/%s", dir, rel);
    snprintf(sub, sizeof(sub), "%s", final);
    char *slash = strrchr(sub, '/');
    if (slash) {
        *slash = '\0';
        if (!mkdirs(sub))
            return NULL;
    }
    char tmp[PATH_MAX + 80];
    snprintf(tmp, sizeof(tmp), "%s.tmp", final);
    FILE *f = fopen(tmp, "w");
    if (!f)
        fprintf(stderr, "kitheme-export: %s: %s\n", tmp, strerror(errno));
    return f;
}

static int close_out(FILE *f, const char *final)
{
    char tmp[PATH_MAX + 80];
    snprintf(tmp, sizeof(tmp), "%s.tmp", final);
    if (fclose(f) != 0 || rename(tmp, final) != 0) {
        fprintf(stderr, "kitheme-export: writing %s failed\n", final);
        remove(tmp);
        return 0;
    }
    return 1;
}

/* ---- index.theme ---- */

static int write_index(const char *dir, const char *name)
{
    char path[PATH_MAX + 64];
    FILE *f = open_out(dir, "index.theme", path, sizeof(path));
    if (!f)
        return 0;
    fprintf(f, "[Desktop Entry]\nType=X-GNOME-Metatheme\nName=%s\n"
               "Comment=KiDesktop theme for GTK2, GTK3, GTK4 and Qt (generated by kitheme-export)\n"
               "Encoding=UTF-8\n\n[X-GNOME-Metatheme]\nGtkTheme=%s\n", name, name);
    return close_out(f, path);
}

