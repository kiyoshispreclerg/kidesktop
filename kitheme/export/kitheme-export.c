static int write_css(const char *dir, const KtTheme *t, int v4)
{
    char path[PATH_MAX + 64];
    FILE *f = open_out(dir, v4 ? "gtk-4.0/gtk.css" : "gtk-3.0/gtk.css", path, sizeof(path));
    if (!f)
        return 0;
    Css s;
    css_colors(t, &s);
    Nodes n3 = {0, "check", "radio", "menu, .menu, .context-menu", "menu menuitem", "menuitem check", "menuitem radio",
                "button:focus"};
    Nodes n4 = {1, "check", "radio", "popover.menu > contents, popover > contents", "popover.menu modelbutton",
                "popover.menu check", "popover.menu radio", "button:focus-visible"};
    const Nodes *n = v4 ? &n4 : &n3;

    fprintf(f, "/* KiTheme %s -- generated by kitheme-export from kitheme.conf, do not edit. */\n", v4 ? "GTK4" : "GTK3");
    fprintf(f, "@import url(\"%s\");\n\n",
            v4 ? "resource:///org/gtk/libgtk/theme/Default/Default-light.css"
               : "resource:///org/gtk/libgtk/theme/Adwaita/gtk-contained.css");
    /* Named colors applications use in their own CSS (GTK3 and libadwaita
     * names). */
    fprintf(f,
            "@define-color theme_bg_color %s;\n@define-color theme_fg_color %s;\n"
            "@define-color theme_base_color %s;\n@define-color theme_text_color %s;\n"
            "@define-color theme_selected_bg_color %s;\n@define-color theme_selected_fg_color %s;\n"
            "@define-color insensitive_fg_color %s;\n@define-color borders %s;\n"
            "@define-color theme_tooltip_bg_color %s;\n@define-color theme_tooltip_fg_color %s;\n"
            "@define-color accent_color %s;\n@define-color accent_bg_color %s;\n@define-color accent_fg_color %s;\n"
            "@define-color window_bg_color %s;\n@define-color window_fg_color %s;\n"
            "@define-color view_bg_color %s;\n@define-color view_fg_color %s;\n"
            "@define-color popover_bg_color %s;\n@define-color popover_fg_color %s;\n\n",
            s.window_bg, s.window_fg, s.base_bg, s.base_fg, s.sel_bg, s.sel_fg, s.dim_fg, s.border,
            s.tip_bg, s.tip_fg, s.accent, s.sel_bg, s.sel_fg, s.window_bg, s.window_fg, s.base_bg, s.base_fg,
            s.menu_bg, s.menu_fg);
    fprintf(f, "window, .background, dialog { background-color: %s; color: %s; }\n"
               "label { color: inherit; }\n"
               ".view, textview text, treeview.view, iconview, list, listview, columnview, .content-view { background-color: %s; color: %s; }\n"
               "*:disabled { color: %s; }\n\n",
            s.window_bg, s.window_fg, s.base_bg, s.base_fg, s.dim_fg);
    css_button(f, t, &s, n);
    css_entry(f, t, &s);
    css_checks(f, t, n);
    css_progress(f, t, &s, v4);
    if (!v4) /* GTK4 draws the text before the trough: it would be hidden */
        css_progress_text(f, t, &s);
    css_scrollbar(f, t, &s, v4);
    css_misc(f, t, &s, n);
    return close_out(f, path);
}

/* ---- live refresh of running GTK2 applications ---- */

static void notify_gtk2(void)
{
    Display *dpy = XOpenDisplay(NULL);
    if (!dpy)
        return;
    Atom read_rc = XInternAtom(dpy, "_GTK_READ_RCFILES", False);
    Window root = DefaultRootWindow(dpy), r, p, *kids = NULL;
    unsigned int n = 0;
    XEvent ev;
    memset(&ev, 0, sizeof(ev));
    ev.xclient.type = ClientMessage;
    ev.xclient.message_type = read_rc;
    ev.xclient.format = 8;
    /* Every top-level and, behind reparenting window managers, the frames'
     * children -- the same windows gdk_event_send_clientmessage_toall()
     * reaches. */
    if (XQueryTree(dpy, root, &r, &p, &kids, &n)) {
        for (unsigned int i = 0; i < n; i++) {
            ev.xclient.window = kids[i];
            XSendEvent(dpy, kids[i], False, NoEventMask, &ev);
            Window *sub = NULL;
            unsigned int ns = 0;
            if (XQueryTree(dpy, kids[i], &r, &p, &sub, &ns)) {
                for (unsigned int j = 0; j < ns; j++) {
                    ev.xclient.window = sub[j];
                    XSendEvent(dpy, sub[j], False, NoEventMask, &ev);
                }
                if (sub)
                    XFree(sub);
            }
        }
        if (kids)
            XFree(kids);
    }
    XCloseDisplay(dpy);
}

static int write_sample(const KtTheme *t, const char *png)
{
    cairo_surface_t *s = cairo_image_surface_create(CAIRO_FORMAT_ARGB32, 480, 400);
    cairo_t *cr = cairo_create(s);
    kt_draw_sample(t, cr, 480, 400);
    cairo_destroy(cr);
    int ok = cairo_surface_write_to_png(s, png) == CAIRO_STATUS_SUCCESS;
    cairo_surface_destroy(s);
    if (!ok)
        fprintf(stderr, "kitheme-export: could not write %s\n", png);
    return ok;
}

static void usage(void)
{
    fprintf(stderr, "usage: kitheme-export [--conf FILE | --preset NAME] [--dest DIR] [--name NAME]\n"
                    "                      [--sample FILE.png] [--notify] [--version]\n");
}

int main(int argc, char **argv)
{
    const char *conf = NULL, *preset = NULL, *dest = NULL, *name = "KiTheme", *sample = NULL;
    int notify = 0;
    for (int i = 1; i < argc; i++) {
        const char *a = argv[i];
        const char *next = i + 1 < argc ? argv[i + 1] : NULL;
        if (!strcmp(a, "--conf") && next)
            conf = argv[++i];
        else if (!strcmp(a, "--preset") && next)
            preset = argv[++i];
        else if (!strcmp(a, "--dest") && next)
            dest = argv[++i];
        else if (!strcmp(a, "--name") && next)
            name = argv[++i];
        else if (!strcmp(a, "--sample") && next)
            sample = argv[++i];
        else if (!strcmp(a, "--notify"))
            notify = 1;
        else if (!strcmp(a, "--version")) {
            printf("kitheme-export %s\n", KITHEME_VERSION);
            return 0;
        }
        else {
            usage();
            return 2;
        }
    }

    KtTheme t;
    if (preset) {
        if (!kt_theme_load_preset(&t, preset)) {
            fprintf(stderr, "kitheme-export: preset '%s' not found\n", preset);
            return 1;
        }
    } else if (conf) {
        if (!kt_theme_load_file(&t, conf)) {
            fprintf(stderr, "kitheme-export: cannot read %s\n", conf);
            return 1;
        }
    } else {
        kt_theme_load_user(&t);
    }

    if (sample)
        return write_sample(&t, sample) ? 0 : 1;

    char dir[PATH_MAX];
    if (dest) {
        snprintf(dir, sizeof(dir), "%s", dest);
    } else {
        const char *home = getenv("HOME");
        if (!home) {
            fprintf(stderr, "kitheme-export: HOME is not set\n");
            return 1;
        }
        snprintf(dir, sizeof(dir), "%s/.themes/%s", home, name);
    }
    if (!mkdirs(dir))
        return 1;
    int ok = write_index(dir, name) && write_gtkrc(dir, &t) && write_assets(dir, &t) &&
             write_css(dir, &t, 0) && write_css(dir, &t, 1);
    if (ok && notify)
        notify_gtk2();
    return ok ? 0 : 1;
}
