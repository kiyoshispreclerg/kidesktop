/* ---- PNG assets for GTK3/GTK4 ---- */

typedef void (*DrawFn)(const KtTheme *, cairo_t *, double, double, double, double, unsigned);

static int write_png(const char *dir, const char *name, int scale, const KtTheme *t, DrawFn fn, unsigned st)
{
    int s = t->check_size;
    cairo_surface_t *surf = cairo_image_surface_create(CAIRO_FORMAT_ARGB32, s * scale, s * scale);
    cairo_t *cr = cairo_create(surf);
    cairo_scale(cr, scale, scale);
    fn(t, cr, 0, 0, s, s, st);
    cairo_destroy(cr);
    char path[PATH_MAX + 128];
    snprintf(path, sizeof(path), "%s/assets/%s%s.png", dir, name, scale > 1 ? "@2" : "");
    cairo_status_t ok = cairo_surface_write_to_png(surf, path);
    cairo_surface_destroy(surf);
    if (ok != CAIRO_STATUS_SUCCESS) {
        fprintf(stderr, "kitheme-export: %s: %s\n", path, cairo_status_to_string(ok));
        return 0;
    }
    return 1;
}

static const struct {
    const char *suffix;
    unsigned st;
} asset_states[] = {
    {"", 0}, {"-hover", KT_HOVER}, {"-disabled", KT_DISABLED},
    {"-checked", KT_CHECKED}, {"-checked-hover", KT_CHECKED | KT_HOVER}, {"-checked-disabled", KT_CHECKED | KT_DISABLED},
    {"-mixed", KT_MIXED}, {"-mixed-hover", KT_MIXED | KT_HOVER}, {"-mixed-disabled", KT_MIXED | KT_DISABLED},
};

static int write_assets(const char *dir, const KtTheme *t)
{
    char adir[PATH_MAX + 16];
    snprintf(adir, sizeof(adir), "%s/assets", dir);
    if (!mkdirs(adir))
        return 0;
    int ok = 1;
    for (size_t i = 0; i < sizeof(asset_states) / sizeof(asset_states[0]); i++) {
        for (int scale = 1; scale <= 2; scale++) {
            char name[64];
            snprintf(name, sizeof(name), "check%s", asset_states[i].suffix);
            ok &= write_png(dir, name, scale, t, kt_draw_check, asset_states[i].st);
            snprintf(name, sizeof(name), "radio%s", asset_states[i].suffix);
            ok &= write_png(dir, name, scale, t, kt_draw_radio, asset_states[i].st);
        }
    }
    /* Marks alone, for menus: in the menu color and the highlighted one. */
    KtTheme m = *t;
    for (int scale = 1; scale <= 2; scale++) {
        m.base_fg = t->menu_fg;
        ok &= write_png(dir, "menu-check", scale, &m, kt_draw_check, KT_CHECKED | KT_NOBOX);
        ok &= write_png(dir, "menu-radio", scale, &m, kt_draw_radio, KT_CHECKED | KT_NOBOX);
        m.base_fg = t->selection_fg;
        ok &= write_png(dir, "menu-check-hover", scale, &m, kt_draw_check, KT_CHECKED | KT_NOBOX);
        ok &= write_png(dir, "menu-radio-hover", scale, &m, kt_draw_radio, KT_CHECKED | KT_NOBOX);
    }
    return ok;
}

/* ---- GTK3/GTK4 CSS ---- */

typedef struct {
    char window_bg[32], window_fg[32], base_bg[32], base_fg[32], button_bg[32], button_fg[32];
    char sel_bg[32], sel_fg[32], accent[32], accent_soft[32], progress[32], menu_bg[32], menu_fg[32];
    char tip_bg[32], tip_fg[32], dim_fg[32], dis_bg[32];
    char border[32], border_dis[32], hilite[32], inner_shadow[32], drop[32];
    char btn_top[32], btn_bot[32], btn_hover_top[32], btn_hover_bot[32], btn_down_top[32], btn_down_bot[32];
    char trough[32], prog_top[32], prog_bot[32], prog_border[32], tab_bg[32], tab_hover[32];
    char sel_top[32], sel_bot[32], menu_top[32], menu_bot[32];
    /* classic bevel */
    char hl[32], light[32], shadow[32], dark[32];
    int r;
} Css;

static void c(char *out, KtColor col)
{
    kt_color_css(col, out, 32);
}

static void css_colors(const KtTheme *t, Css *s)
{
    static const KtColor W = {1, 1, 1, 1}, B = {0, 0, 0, 1};
    double g = t->gradient, rl = t->relief;
    c(s->window_bg, t->window_bg);
    c(s->window_fg, t->window_fg);
    c(s->base_bg, t->base_bg);
    c(s->base_fg, t->base_fg);
    c(s->button_bg, t->button_bg);
    c(s->button_fg, t->button_fg);
    c(s->sel_bg, t->selection_bg);
    c(s->sel_fg, t->selection_fg);
    c(s->accent, t->accent);
    c(s->accent_soft, kt_alpha(kt_shade(t->accent, 1.2), 0.6));
    c(s->progress, t->progress);
    c(s->menu_bg, t->menu_bg);
    c(s->menu_fg, t->menu_fg);
    c(s->tip_bg, t->tooltip_bg);
    c(s->tip_fg, t->tooltip_fg);
    c(s->dim_fg, kt_mix(t->window_fg, t->window_bg, 0.55));
    c(s->dis_bg, kt_mix(t->button_bg, t->window_bg, 0.5));
    c(s->border, kt_alpha(kt_shade(t->button_bg, 0.55), 0.55 + 0.35 * rl));
    c(s->border_dis, kt_alpha(kt_shade(t->button_bg, 0.55), 0.35));
    c(s->hilite, kt_alpha(W, 0.75 * rl));
    c(s->inner_shadow, kt_alpha(B, 0.16 * rl));
    c(s->drop, kt_alpha(B, 0.12 * t->shadow));
    c(s->btn_top, kt_shade(t->button_bg, 1 + 0.10 * g));
    c(s->btn_bot, kt_shade(t->button_bg, 1 - 0.09 * g));
    KtColor hb = kt_shade(t->button_bg, 1.04);
    c(s->btn_hover_top, kt_shade(hb, 1 + 0.10 * g));
    c(s->btn_hover_bot, kt_shade(hb, 1 - 0.09 * g));
    c(s->btn_down_top, kt_shade(t->button_bg, 1 - 0.14 * g - 0.06));
    c(s->btn_down_bot, kt_shade(t->button_bg, 1 + 0.04 * g));
    c(s->trough, t->style == KT_STYLE_FLAT ? kt_shade(t->window_bg, 0.88) : kt_mix(t->window_bg, B, 0.04));
    c(s->prog_top, kt_shade(t->progress, 1 + 0.18 * g));
    c(s->prog_bot, kt_shade(t->progress, 1 - 0.15 * g));
    c(s->prog_border, kt_alpha(kt_shade(t->progress, 0.6), 0.8));
    c(s->tab_bg, kt_shade(t->window_bg, 0.91));
    c(s->tab_hover, kt_shade(t->window_bg, 0.97));
    c(s->sel_top, kt_shade(t->selection_bg, 1 + 0.10 * g));
    c(s->sel_bot, kt_shade(t->selection_bg, 1 - 0.08 * g));
    c(s->menu_top, kt_shade(t->menu_bg, 1 + 0.05 * g));
    c(s->menu_bot, kt_shade(t->menu_bg, 1 - 0.04 * g));
    double k = rl > 0 ? rl : 0.01;
    c(s->hl, kt_mix(t->window_bg, W, 1.0 * k));
    c(s->light, kt_mix(t->window_bg, W, 0.45 * k));
    c(s->shadow, kt_mix(t->window_bg, B, 0.33 * k));
    c(s->dark, kt_mix(t->window_bg, B, 1.0 * k));
    s->r = t->style == KT_STYLE_CLASSIC ? 0 : (int)(t->radius + 0.5);
}

/* Selectors that differ between GTK3 and GTK4. */
typedef struct {
    int v4;
    const char *check, *radio, *menu, *menuitem, *menu_check, *menu_radio, *focus;
} Nodes;

static void css_button(FILE *f, const KtTheme *t, const Css *s, const Nodes *n)
{
    const char *btn = "button:not(.flat):not(.titlebutton)";
    if (t->style == KT_STYLE_CLASSIC) {
        fprintf(f,
                "%s, combobox button.combo {\n"
                "  background-image: none; background-color: %s; color: %s;\n"
                "  border: 1px solid; border-color: %s %s %s %s; border-radius: 0;\n"
                "  box-shadow: inset 1px 1px %s, inset -1px -1px %s; text-shadow: none; -gtk-icon-shadow: none;\n}\n"
                "%s:hover { background-color: %s; }\n"
                "%s:active, %s:checked {\n"
                "  border-color: %s; box-shadow: inset 1px 1px %s; background-image: none;\n}\n"
                "%s:disabled { color: %s; background-image: none; }\n"
                "button.default { border-color: %s; box-shadow: inset 1px 1px %s, inset -1px -1px %s, inset 2px 2px %s, inset -2px -2px %s; }\n"
                "button.flat:hover { background-image: none; border: 1px solid; border-color: %s %s %s %s;"
                " box-shadow: none; }\n",
                btn, s->button_bg, s->button_fg, s->light, s->dark, s->dark, s->light, s->hl, s->shadow,
                btn, s->button_bg,
                btn, btn, s->dark, s->shadow,
                btn, s->dim_fg,
                s->dark, s->dark, s->dark, s->hl, s->shadow,
                s->hl, s->shadow, s->shadow, s->hl);
        fprintf(f, "%s { outline: 1px dotted %s; outline-offset: -4px; }\n", n->focus, s->button_fg);
        return;
    }
    if (t->style == KT_STYLE_FLAT) {
        fprintf(f,
                "%s, combobox button.combo {\n"
                "  background-image: none; background-color: %s; color: %s;\n"
                "  border: 1px solid %s; border-radius: %dpx; box-shadow: none; text-shadow: none; -gtk-icon-shadow: none;\n}\n"
                "%s:hover { border-color: %s; }\n"
                "%s:active, %s:checked { background-color: %s; background-image: none; }\n"
                "%s:disabled { background-color: %s; color: %s; border-color: %s; }\n",
                btn, s->button_bg, s->button_fg, s->border, s->r,
                btn, t->hover_glow ? s->accent : s->border,
                btn, btn, s->btn_down_top,
                btn, s->dis_bg, s->dim_fg, s->border_dis);
        fprintf(f, "%s { outline: none; border-color: %s; }\n", n->focus, s->accent);
        return;
    }
    fprintf(f,
            "%s, combobox button.combo {\n"
            "  background-color: %s; background-image: linear-gradient(to bottom, %s, %s); color: %s;\n"
            "  border: 1px solid %s; border-radius: %dpx;\n"
            "  box-shadow: inset 0 1px %s, 0 1px 1px %s; text-shadow: none; -gtk-icon-shadow: none;\n}\n"
            "%s:hover {\n"
            "  background-image: linear-gradient(to bottom, %s, %s);\n"
            "  box-shadow: inset 0 1px %s, 0 0 0 1px %s;\n}\n"
            "%s:active, %s:checked {\n"
            "  background-image: linear-gradient(to bottom, %s, %s);\n"
            "  box-shadow: inset 0 1px 2px %s;\n}\n"
            "%s:disabled {\n"
            "  background-image: none; background-color: %s; color: %s; border-color: %s; box-shadow: none;\n}\n"
            "button.default { border-color: %s; }\n",
            btn, s->button_bg, s->btn_top, s->btn_bot, s->button_fg, s->border, s->r, s->hilite, s->drop,
            btn, s->btn_hover_top, s->btn_hover_bot, s->hilite, t->hover_glow ? s->accent_soft : "transparent",
            btn, btn, s->btn_down_top, s->btn_down_bot, s->inner_shadow,
            btn, s->dis_bg, s->dim_fg, s->border_dis,
            s->accent);
    if (t->focus == KT_FOCUS_GLOW)
        fprintf(f, "%s { outline: none; box-shadow: inset 0 1px %s, 0 0 0 1px %s; }\n", n->focus, s->hilite, s->accent);
}

static void css_checks(FILE *f, const KtTheme *t, const Nodes *n)
{
    int s = t->check_size;
    const char *names[2] = {"check", "radio"};
    const char *sel[2] = {n->check, n->radio};
    for (int k = 0; k < 2; k++) {
        fprintf(f, "%s {\n  min-width: %dpx; min-height: %dpx; margin: 0 4px 0 0;\n"
                   "  background-image: none; background-color: transparent; border: none; box-shadow: none;"
                   " -gtk-icon-shadow: none; color: transparent;\n}\n",
                sel[k], s, s);
        static const struct {
            const char *pseudo, *suffix;
        } st[] = {
            {"", ""}, {":hover", "-hover"}, {":disabled", "-disabled"},
            {":checked", "-checked"}, {":checked:hover", "-checked-hover"}, {":checked:disabled", "-checked-disabled"},
            {":indeterminate", "-mixed"}, {":indeterminate:hover", "-mixed-hover"}, {":indeterminate:disabled", "-mixed-disabled"},
        };
        for (size_t i = 0; i < sizeof(st) / sizeof(st[0]); i++) {
            if (n->v4)
                fprintf(f, "%s%s { -gtk-icon-source: url(\"../assets/%s%s.png\"); }\n", sel[k], st[i].pseudo, names[k], st[i].suffix);
            else
                fprintf(f, "%s%s { -gtk-icon-source: -gtk-scaled(url(\"../assets/%s%s.png\"), url(\"../assets/%s%s@2.png\")); }\n",
                        sel[k], st[i].pseudo, names[k], st[i].suffix, names[k], st[i].suffix);
        }
    }
    /* In menus: the mark alone. */
    const char *msel[2] = {n->menu_check, n->menu_radio};
    for (int k = 0; k < 2; k++) {
        if (n->v4) {
            fprintf(f, "%s:not(:checked) { -gtk-icon-source: none; }\n", msel[k]);
            fprintf(f, "%s:checked { -gtk-icon-source: url(\"../assets/menu-%s.png\"); }\n", msel[k], names[k]);
        } else {
            fprintf(f, "%s:not(:checked) { -gtk-icon-source: none; }\n", msel[k]);
            fprintf(f, "%s:checked { -gtk-icon-source: -gtk-scaled(url(\"../assets/menu-%s.png\"), url(\"../assets/menu-%s@2.png\")); }\n",
                    msel[k], names[k], names[k]);
            fprintf(f, "menuitem:hover %s:checked { -gtk-icon-source: -gtk-scaled(url(\"../assets/menu-%s-hover.png\"), url(\"../assets/menu-%s-hover@2.png\")); }\n",
                    msel[k], names[k], names[k]);
        }
    }
}

