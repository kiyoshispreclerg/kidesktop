/* kitheme-export - writes the KiTheme theme directory from a kitheme.conf.
 *
 *   kitheme-export [--conf FILE | --preset NAME] [--dest DIR] [--name NAME]
 *                  [--sample FILE.png] [--notify]
 *
 * Default source: the user's kitheme.conf (or the default preset); default
 * destination: ~/.themes/KiTheme, which GTK2, GTK3 and GTK4 all search
 * before the system theme directories. It contains
 *   index.theme
 *   gtk-2.0/gtkrc     metrics and roles for the GTK2 engine (which reads the
 *                     colors itself, see gtk2/kt_gtk2.c)
 *   gtk-3.0/gtk.css   on top of GTK3's built-in Adwaita
 *   gtk-4.0/gtk.css   on top of GTK4's built-in Default theme
 *   assets/ (PNG)     check boxes and radio buttons, drawn by libkitheme
 * GTK3/GTK4 have no engines: their part is static CSS, so it costs those
 * applications nothing at run time beyond parsing the file.
 *
 * --notify asks running GTK2 applications to re-read their rc files
 * (_GTK_READ_RCFILES); GTK3/4 ones reload when the theme name changes,
 * which kiconfd handles.
 * The build runs it with --preset oxygen --dest <tree> to make the copy
 * installed in /usr/share/themes. */
