/* Shared by both configs: trimmed "key = value" or "key=value" lines,
 * '#' comments, blank lines skipped. Matches kistoryd/kimemoryd's own
 * loader (see their READMEs' Config tables). */
static void conf_load_kv(const char *filename, void (*set)(void *c, const char *key, const char *val), void *c)
{
    char path[PATH_MAX];
    resolve_path(filename, path, sizeof(path));
    FILE *f = fopen(path, "r");
    if (!f) {
        return;
    }
    char line[512];
    while (fgets(line, sizeof(line), f)) {
        char *l = trim(line);
        if (!*l || *l == '#') {
            continue;
        }
        char *eq = strchr(l, '=');
        if (!eq) {
            continue;
        }
        *eq = '\0';
        char *key = trim(l);
        char *val = trim(eq + 1);
        set(c, key, val);
    }
    fclose(f);
}

static void kistory_defaults(KistoryConfig *c)
{
    memset(c, 0, sizeof(*c));
    c->min_dwell_s = 3;
    c->retention_days = 90;
    c->fd_sampling = 1;
    snprintf(c->exclude, sizeof(c->exclude), "keepassxc,KeePassXC");
    snprintf(c->guard_actions, sizeof(c->guard_actions), "SCREEN,RECORD,INPUT_INJECT,INPUT");
}

static void kistory_set_kv(void *vc, const char *key, const char *val)
{
    KistoryConfig *c = vc;
    if (!strcmp(key, "min_dwell_s")) {
        c->min_dwell_s = atoi(val);
    } else if (!strcmp(key, "retention_days")) {
        c->retention_days = atoi(val);
    } else if (!strcmp(key, "fd_sampling")) {
        c->fd_sampling = atoi(val) != 0;
    } else if (!strcmp(key, "exclude")) {
        snprintf(c->exclude, sizeof(c->exclude), "%s", val);
    } else if (!strcmp(key, "title_only_exclude")) {
        snprintf(c->title_only_exclude, sizeof(c->title_only_exclude), "%s", val);
    } else if (!strcmp(key, "private_title_regex")) {
        snprintf(c->private_title_regex, sizeof(c->private_title_regex), "%s", val);
    } else if (!strcmp(key, "guard_actions")) {
        snprintf(c->guard_actions, sizeof(c->guard_actions), "%s", val);
    }
}

static void kistory_load(KistoryConfig *c)
{
    kistory_defaults(c);
    conf_load_kv("kistory.conf", kistory_set_kv, c);
}

static void kistory_save(const KistoryConfig *c)
{
    char path[PATH_MAX];
    resolve_path("kistory.conf", path, sizeof(path));
    char tmp[PATH_MAX];
    snprintf(tmp, sizeof(tmp), "%s.tmp", path);
    FILE *f = fopen(tmp, "w");
    if (!f) {
        g_warning("kiconf: could not write '%s': %s", tmp, strerror(errno));
        return;
    }
    fprintf(f, "# kistory config -- generated by kiconf's Historico tab.\n");
    fprintf(f, "# See kistory/README.md for what each key does.\n");
    fprintf(f, "min_dwell_s=%d\n", c->min_dwell_s);
    fprintf(f, "retention_days=%d\n", c->retention_days);
    fprintf(f, "fd_sampling=%d\n", c->fd_sampling);
    fprintf(f, "exclude=%s\n", c->exclude);
    fprintf(f, "title_only_exclude=%s\n", c->title_only_exclude);
    fprintf(f, "private_title_regex=%s\n", c->private_title_regex);
    fprintf(f, "guard_actions=%s\n", c->guard_actions);
    fclose(f);
    if (rename(tmp, path) != 0) {
        g_warning("kiconf: could not save '%s': %s", path, strerror(errno));
    }
}

