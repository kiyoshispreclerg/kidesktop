/* kiconf - Historico tab: kistory.conf and kimemory.conf.
 * See kiconf.c's top doc comment for the overall design.
 *
 * Both daemons read $XDG_CONFIG_HOME/<name>.conf directly (key=value,
 * SIGHUP reloads) and have no control socket for settings -- kimemoryd's
 * control socket (see kimemory/README.md) only serves runtime queries
 * (LIST/GET/PASTE/...), and kistoryd has none yet. So this tab edits the
 * conf files the same way the Energia tab edits kiconfd-nightlight.conf,
 * instead of going over a socket like the Permissoes tab does for
 * xisguard. "Espaco em disco" and "Limpar" shell out to the `kistory`/
 * `kimemory` CLIs (stats/purge, status/clear), which already do this
 * correctly (atomic rewrite, flock) -- reimplementing that here would
 * just be a second, divergent copy of the same logic.
 */
