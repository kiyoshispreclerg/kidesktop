/* kiconf - Energia tab: night light schedule, DPMS and screensaver.
 * See kiconf.c's top doc comment for the overall design.
 *
 * Writes $XDG_CONFIG_HOME/kiconfd-nightlight.conf, the same file
 * xisserve's --energy page writes (its checkbox+slider there is the
 * "manual, right now" side of this feature -- see xisserve/PROTOCOL.md's
 * `--energy` entry). This tab is the only place the schedule itself
 * (start/end/temperature) is set; kiconfd is the only thing that reads
 * it back and applies it, at the configured times, via `xsct`
 * (https://github.com/faf0/sct) -- see kiconfd.c's own doc comment for
 * the daemon side.
 *
 * Gated on `xsct` being installed, same have_cmd()-and-status-label
 * pattern system.c uses for localectl/timedatectl: the tab still opens
 * and shows the schedule (so a config made before installing xsct isn't
 * lost), but Aplicar is disabled and a message explains why.
 */
#include "../common.h"
#include "../tabs.h"

#include <errno.h>
#include <limits.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define NIGHTLIGHT_TEMP_MIN 2700
#define NIGHTLIGHT_TEMP_MAX 6500
#define NIGHTLIGHT_TEMP_DEFAULT 4000

static GtkWidget *g_status_label;
static GtkWidget *g_enabled_chk;
static GtkWidget *g_start_hour_spin, *g_start_min_spin;
static GtkWidget *g_end_hour_spin, *g_end_min_spin;
static GtkWidget *g_temp_spin;

static GtkWidget *g_lid_combo, *g_power_combo;
static GtkWidget *g_dpms_enabled_chk, *g_dpms_standby_spin, *g_dpms_suspend_spin, *g_dpms_off_spin;
static GtkWidget *g_saver_timeout_spin, *g_saver_cycle_spin, *g_prefer_blank_chk;

/* What kiconfd does on lid close / power button; the first entry of each
 * table is the default ("system" = leave it to logind/acpid). */
typedef struct {
    const char *value;
    const char *label;
} ActionChoice;

static const ActionChoice LID_CHOICES[] = {
    {"system", N_("Padrao do sistema")},
    {"suspend", N_("Suspender")},
    {"lock", N_("Bloquear a tela")},
    {"nothing", N_("Nao fazer nada")},
};
static const ActionChoice POWER_CHOICES[] = {
    {"system", N_("Padrao do sistema")},
    {"ask", N_("Perguntar o que fazer")},
    {"poweroff", N_("Desligar direto")},
    {"suspend", N_("Suspender")},
    {"nothing", N_("Nao fazer nada")},
};
#define N_LID_CHOICES ((int)(sizeof(LID_CHOICES) / sizeof(LID_CHOICES[0])))
#define N_POWER_CHOICES ((int)(sizeof(POWER_CHOICES) / sizeof(POWER_CHOICES[0])))

typedef struct {
    char lid_action[16], power_action[16];
    int dpms_enabled, dpms_standby, dpms_suspend, dpms_off;
    int saver_timeout, saver_cycle, prefer_blanking;
} PowerState;
static PowerState g_power_baseline;

typedef struct {
    int enabled;
    char start[8];
    char end[8];
    int temp;
} NightlightConfig;

static int have_cmd(const char *name)
{
    char out[PATH_MAX];
    char *argv[] = {"which", (char *)name, NULL};
    return run_capture(argv, out, sizeof(out)) && out[0];
}

static void nightlight_defaults(NightlightConfig *c)
{
    c->enabled = 0;
    snprintf(c->start, sizeof(c->start), "20:00");
    snprintf(c->end, sizeof(c->end), "06:00");
    c->temp = NIGHTLIGHT_TEMP_DEFAULT;
}

static void nightlight_load(NightlightConfig *c)
{
    nightlight_defaults(c);
    char path[PATH_MAX];
    resolve_path("kiconfd-nightlight.conf", path, sizeof(path));
    FILE *f = fopen(path, "r");
    if (!f) {
        return;
    }
    char line[128];
    while (fgets(line, sizeof(line), f)) {
        char *l = trim(line);
        if (!*l || *l == '#') {
            continue;
        }
        char *eq = strchr(l, '=');
        if (!eq) {
            continue;
        }
        *eq = '\0';
        char *key = trim(l);
        char *val = trim(eq + 1);
        if (!strcmp(key, "enabled")) {
            c->enabled = atoi(val) ? 1 : 0;
        } else if (!strcmp(key, "start")) {
            snprintf(c->start, sizeof(c->start), "%s", val);
        } else if (!strcmp(key, "end")) {
            snprintf(c->end, sizeof(c->end), "%s", val);
        } else if (!strcmp(key, "temp")) {
            c->temp = atoi(val);
        }
    }
    fclose(f);
}

static void nightlight_save(const NightlightConfig *c)
{
    char path[PATH_MAX];
    resolve_path("kiconfd-nightlight.conf", path, sizeof(path));
    char tmp[PATH_MAX + 8]; /* path + ".tmp" */
    snprintf(tmp, sizeof(tmp), "%s.tmp", path);
    FILE *f = fopen(tmp, "w");
    if (!f) {
        g_warning("kiconf: could not write '%s': %s", tmp, strerror(errno));
        return;
    }
    fprintf(f, "# kiconfd night light schedule -- generated by kiconf's Energia tab,\n");
    fprintf(f, "# applied via xsct by kiconfd. xisserve's --energy page can also flip\n");
    fprintf(f, "# 'enabled' (its checkbox) and 'temp' (its slider, when not automatic).\n");
    fprintf(f, "enabled = %d\n", c->enabled);
    fprintf(f, "start = %s\n", c->start);
    fprintf(f, "end = %s\n", c->end);
    fprintf(f, "temp = %d\n", c->temp);
    fclose(f);
    if (rename(tmp, path) != 0) {
        g_warning("kiconf: could not save '%s': %s", path, strerror(errno));
    }
}

/* "HH:MM" -> two spin buttons. Malformed/out-of-range values fall back
 * to 0:00 rather than rejecting the whole config over one bad field. */
static void set_time_spins(const char *hhmm, GtkWidget *hour_spin, GtkWidget *min_spin)
{
    int h = 0, m = 0;
    sscanf(hhmm, "%d:%d", &h, &m);
    if (h < 0 || h > 23) {
        h = 0;
    }
    if (m < 0 || m > 59) {
        m = 0;
    }
    gtk_spin_button_set_value(GTK_SPIN_BUTTON(hour_spin), h);
    gtk_spin_button_set_value(GTK_SPIN_BUTTON(min_spin), m);
}

static void get_time_spins(char *out, size_t outsz, GtkWidget *hour_spin, GtkWidget *min_spin)
{
    snprintf(out, outsz, "%02d:%02d",
             gtk_spin_button_get_value_as_int(GTK_SPIN_BUTTON(hour_spin)),
             gtk_spin_button_get_value_as_int(GTK_SPIN_BUTTON(min_spin)));
}

/* lid_action / power_button_action from kiconfd-power.conf. */
static void load_actions(PowerState *p)
{
    snprintf(p->lid_action, sizeof(p->lid_action), "system");
    snprintf(p->power_action, sizeof(p->power_action), "system");
    char path[PATH_MAX];
    resolve_path("kiconfd-power.conf", path, sizeof(path));
    FILE *f = fopen(path, "r");
    if (!f) {
        return;
    }
    char line[128];
    while (fgets(line, sizeof(line), f)) {
        char *l = trim(line);
        char *eq = strchr(l, '=');
        if (!*l || *l == '#' || !eq) {
            continue;
        }
        *eq = '\0';
        char *key = trim(l);
        char *val = trim(eq + 1);
        if (!strcmp(key, "lid_action")) {
            snprintf(p->lid_action, sizeof(p->lid_action), "%s", val);
        } else if (!strcmp(key, "power_button_action")) {
            snprintf(p->power_action, sizeof(p->power_action), "%s", val);
        }
    }
    fclose(f);
}

static void detect_power_xset(PowerState *p)
{
    load_actions(p);
    p->dpms_enabled = 1;
    p->dpms_standby = 0;
    p->dpms_suspend = 0;
    p->dpms_off = 0;
    p->saver_timeout = 0;
    p->saver_cycle = 600;
    p->prefer_blanking = 1;
    char *argv[] = {"xset", "q", NULL};
    char out[8192];
    if (!run_capture(argv, out, sizeof(out))) {
        return;
    }
    char *p2;
    if ((p2 = strstr(out, "Standby:"))) {
        sscanf(p2, "Standby:%d Suspend:%d Off:%d", &p->dpms_standby, &p->dpms_suspend, &p->dpms_off);
    }
    p->dpms_enabled = strstr(out, "DPMS is Enabled") != NULL;
    if ((p2 = strstr(out, "timeout:"))) {
        sscanf(p2, "timeout:%d cycle:%d", &p->saver_timeout, &p->saver_cycle);
    }
    if ((p2 = strstr(out, "prefer blanking:"))) {
        p2 += strlen("prefer blanking:");
        while (*p2 == ' ') {
            p2++;
        }
        p->prefer_blanking = strncmp(p2, "yes", 3) == 0;
    }
}

static void apply_power_diff(const PowerState *cur, const PowerState *base)
{
    if (cur->dpms_enabled != base->dpms_enabled) {
        char *argv[] = {"xset", cur->dpms_enabled ? "+dpms" : "-dpms", NULL};
        run_fire(argv);
    }
    if (cur->dpms_standby != base->dpms_standby || cur->dpms_suspend != base->dpms_suspend ||
        cur->dpms_off != base->dpms_off) {
        char a[16], b[16], c[16];
        snprintf(a, sizeof(a), "%d", cur->dpms_standby);
        snprintf(b, sizeof(b), "%d", cur->dpms_suspend);
        snprintf(c, sizeof(c), "%d", cur->dpms_off);
        char *argv[] = {"xset", "dpms", a, b, c, NULL};
        run_fire(argv);
    }
    if (cur->saver_timeout != base->saver_timeout || cur->saver_cycle != base->saver_cycle) {
        char a[16], b[16];
        snprintf(a, sizeof(a), "%d", cur->saver_timeout);
        snprintf(b, sizeof(b), "%d", cur->saver_cycle);
        char *argv[] = {"xset", "s", a, b, NULL};
        run_fire(argv);
    }
    if (cur->prefer_blanking != base->prefer_blanking) {
        char *argv[] = {"xset", "s", cur->prefer_blanking ? "blank" : "noblank", NULL};
        run_fire(argv);
    }
}

/* Persisted for kiconfd (kiconfd-power.conf), which replays it at each
 * session start -- xset's values don't survive an X server restart. */
static void power_config_save(const PowerState *p)
{
    char path[PATH_MAX];
    resolve_path("kiconfd-power.conf", path, sizeof(path));
    char tmp[PATH_MAX + 8];
    snprintf(tmp, sizeof(tmp), "%s.tmp", path);
    FILE *f = fopen(tmp, "w");
    if (!f) {
        g_warning("kiconf: could not write '%s': %s", tmp, strerror(errno));
        return;
    }
    fprintf(f, "# kiconfd power settings -- generated by kiconf's Energia tab,\n");
    fprintf(f, "# applied by kiconfd at the start of each session.\n");
    fprintf(f, "lid_action = %s\n", p->lid_action);
    fprintf(f, "power_button_action = %s\n", p->power_action);
    fprintf(f, "dpms_enabled = %d\n", p->dpms_enabled ? 1 : 0);
    fprintf(f, "dpms_standby = %d\n", p->dpms_standby);
    fprintf(f, "dpms_suspend = %d\n", p->dpms_suspend);
    fprintf(f, "dpms_off = %d\n", p->dpms_off);
    fprintf(f, "saver_timeout = %d\n", p->saver_timeout);
    fprintf(f, "saver_cycle = %d\n", p->saver_cycle);
    fprintf(f, "prefer_blanking = %d\n", p->prefer_blanking ? 1 : 0);
    fclose(f);
    if (rename(tmp, path) != 0) {
        g_warning("kiconf: could not save '%s': %s", path, strerror(errno));
    }
}

static void apply_cb(GtkWidget *widget, gpointer data)
{
    (void)widget;
    (void)data;

    NightlightConfig c;
    c.enabled = gtk_toggle_button_get_active(GTK_TOGGLE_BUTTON(g_enabled_chk));
    get_time_spins(c.start, sizeof(c.start), g_start_hour_spin, g_start_min_spin);
    get_time_spins(c.end, sizeof(c.end), g_end_hour_spin, g_end_min_spin);
    c.temp = gtk_spin_button_get_value_as_int(GTK_SPIN_BUTTON(g_temp_spin));

    nightlight_save(&c);

    PowerState pcur;
    snprintf(pcur.lid_action, sizeof(pcur.lid_action), "%s",
             LID_CHOICES[MAX(0, gtk_combo_box_get_active(GTK_COMBO_BOX(g_lid_combo)))].value);
    snprintf(pcur.power_action, sizeof(pcur.power_action), "%s",
             POWER_CHOICES[MAX(0, gtk_combo_box_get_active(GTK_COMBO_BOX(g_power_combo)))].value);
    pcur.dpms_enabled = gtk_toggle_button_get_active(GTK_TOGGLE_BUTTON(g_dpms_enabled_chk));
    pcur.dpms_standby = gtk_spin_button_get_value_as_int(GTK_SPIN_BUTTON(g_dpms_standby_spin));
    pcur.dpms_suspend = gtk_spin_button_get_value_as_int(GTK_SPIN_BUTTON(g_dpms_suspend_spin));
    pcur.dpms_off = gtk_spin_button_get_value_as_int(GTK_SPIN_BUTTON(g_dpms_off_spin));
    pcur.saver_timeout = gtk_spin_button_get_value_as_int(GTK_SPIN_BUTTON(g_saver_timeout_spin));
    pcur.saver_cycle = gtk_spin_button_get_value_as_int(GTK_SPIN_BUTTON(g_saver_cycle_spin));
    pcur.prefer_blanking = gtk_toggle_button_get_active(GTK_TOGGLE_BUTTON(g_prefer_blank_chk));
    apply_power_diff(&pcur, &g_power_baseline);
    g_power_baseline = pcur;
    power_config_save(&pcur);
    /* After both files are written: kiconfd re-reads them on SIGHUP. */
    signal_daemon("kiconfd");

    gtk_label_set_text(GTK_LABEL(g_status_label), _("Configuracoes de energia salvas."));
}

GtkWidget *build_energy_tab(void)
{
    GtkWidget *outer = gtk_vbox_new(FALSE, 8);
    gtk_container_set_border_width(GTK_CONTAINER(outer), 12);

    detect_power_xset(&g_power_baseline);

    int have_xsct = have_cmd("xsct");

    g_status_label = gtk_label_new(have_xsct ? "" :
        _("xsct nao encontrado -- instale-o (https://github.com/faf0/sct) para "
          "a luz noturna automatica funcionar. O horario ainda pode ser configurado "
          "e salvo aqui."));
    gtk_misc_set_alignment(GTK_MISC(g_status_label), 0.0, 0.5);
    gtk_label_set_line_wrap(GTK_LABEL(g_status_label), TRUE);
    gtk_box_pack_start(GTK_BOX(outer), g_status_label, FALSE, FALSE, 0);

    NightlightConfig c;
    nightlight_load(&c);

    GtkWidget *box = gtk_vbox_new(FALSE, 6);

    g_enabled_chk = gtk_check_button_new_with_label(_("Ativar luz noturna automatica"));
    gtk_toggle_button_set_active(GTK_TOGGLE_BUTTON(g_enabled_chk), c.enabled);
    gtk_box_pack_start(GTK_BOX(box), g_enabled_chk, FALSE, FALSE, 0);

    GtkWidget *sched_box = gtk_hbox_new(FALSE, 4);
    gtk_box_pack_start(GTK_BOX(sched_box), gtk_label_new(_("Ligar as:")), FALSE, FALSE, 0);
    g_start_hour_spin = gtk_spin_button_new_with_range(0, 23, 1);
    g_start_min_spin = gtk_spin_button_new_with_range(0, 59, 1);
    gtk_box_pack_start(GTK_BOX(sched_box), g_start_hour_spin, FALSE, FALSE, 0);
    gtk_box_pack_start(GTK_BOX(sched_box), gtk_label_new(_(":")), FALSE, FALSE, 0);
    gtk_box_pack_start(GTK_BOX(sched_box), g_start_min_spin, FALSE, FALSE, 0);

    gtk_box_pack_start(GTK_BOX(sched_box), gtk_label_new(_("   Desligar as:")), FALSE, FALSE, 0);
    g_end_hour_spin = gtk_spin_button_new_with_range(0, 23, 1);
    g_end_min_spin = gtk_spin_button_new_with_range(0, 59, 1);
    gtk_box_pack_start(GTK_BOX(sched_box), g_end_hour_spin, FALSE, FALSE, 0);
    gtk_box_pack_start(GTK_BOX(sched_box), gtk_label_new(_(":")), FALSE, FALSE, 0);
    gtk_box_pack_start(GTK_BOX(sched_box), g_end_min_spin, FALSE, FALSE, 0);
    gtk_box_pack_start(GTK_BOX(box), sched_box, FALSE, FALSE, 0);
    a11y_name(g_start_hour_spin, _("Ligar: hora"));
    a11y_name(g_start_min_spin, _("Ligar: minuto"));
    a11y_name(g_end_hour_spin, _("Desligar: hora"));
    a11y_name(g_end_min_spin, _("Desligar: minuto"));
    set_time_spins(c.start, g_start_hour_spin, g_start_min_spin);
    set_time_spins(c.end, g_end_hour_spin, g_end_min_spin);

    GtkWidget *temp_table = gtk_table_new(1, 2, FALSE);
    g_temp_spin = gtk_spin_button_new_with_range(NIGHTLIGHT_TEMP_MIN, NIGHTLIGHT_TEMP_MAX, 100);
    gtk_spin_button_set_value(GTK_SPIN_BUTTON(g_temp_spin), c.temp);
    labeled_row(temp_table, 0, _("Temperatura durante o periodo (K):"), g_temp_spin);
    gtk_box_pack_start(GTK_BOX(box), temp_table, FALSE, FALSE, 0);

    gtk_box_pack_start(GTK_BOX(outer),
                        frame_with(_("Luz noturna (xsct)"), box), FALSE, FALSE, 0);

    GtkWidget *lid_table = gtk_table_new(2, 2, FALSE);
    g_lid_combo = gtk_combo_box_new_text();
    int lid_sel = 0;
    for (int i = 0; i < N_LID_CHOICES; i++) {
        gtk_combo_box_append_text(GTK_COMBO_BOX(g_lid_combo), _(LID_CHOICES[i].label));
        if (!strcmp(LID_CHOICES[i].value, g_power_baseline.lid_action)) {
            lid_sel = i;
        }
    }
    gtk_combo_box_set_active(GTK_COMBO_BOX(g_lid_combo), lid_sel);
    labeled_row(lid_table, 0, _("Ao fechar a tampa:"), g_lid_combo);
    g_power_combo = gtk_combo_box_new_text();
    int power_sel = 0;
    for (int i = 0; i < N_POWER_CHOICES; i++) {
        gtk_combo_box_append_text(GTK_COMBO_BOX(g_power_combo), _(POWER_CHOICES[i].label));
        if (!strcmp(POWER_CHOICES[i].value, g_power_baseline.power_action)) {
            power_sel = i;
        }
    }
    gtk_combo_box_set_active(GTK_COMBO_BOX(g_power_combo), power_sel);
    labeled_row(lid_table, 1, _("Ao apertar o botao de energia:"), g_power_combo);
    gtk_box_pack_start(GTK_BOX(outer), frame_with(_("Tampa e botao de energia"), lid_table), FALSE, FALSE, 0);

    GtkWidget *lid_note = gtk_label_new(
        _("\"Padrao do sistema\" nao mexe em nada (logind/acpid decidem). Qualquer outra opcao "
          "e tratada pelo kiconfd, que tambem impede o logind de agir em duplicidade. "
          "A tampa depende do UPower; o botao precisa que o servidor X entregue a tecla de energia."));
    gtk_misc_set_alignment(GTK_MISC(lid_note), 0.0, 0.5);
    gtk_label_set_line_wrap(GTK_LABEL(lid_note), TRUE);
    gtk_box_pack_start(GTK_BOX(outer), lid_note, FALSE, FALSE, 0);

    GtkWidget *dpms_table = gtk_table_new(4, 2, FALSE);
    g_dpms_enabled_chk = gtk_check_button_new_with_label(_("DPMS habilitado"));
    gtk_toggle_button_set_active(GTK_TOGGLE_BUTTON(g_dpms_enabled_chk), g_power_baseline.dpms_enabled);
    gtk_table_attach(GTK_TABLE(dpms_table), g_dpms_enabled_chk, 0, 2, 0, 1, GTK_FILL, GTK_FILL, 4, 2);
    g_dpms_standby_spin = gtk_spin_button_new_with_range(0, 36000, 10);
    gtk_spin_button_set_value(GTK_SPIN_BUTTON(g_dpms_standby_spin), g_power_baseline.dpms_standby);
    labeled_row(dpms_table, 1, "Standby, s (0=off):", g_dpms_standby_spin);
    g_dpms_suspend_spin = gtk_spin_button_new_with_range(0, 36000, 10);
    gtk_spin_button_set_value(GTK_SPIN_BUTTON(g_dpms_suspend_spin), g_power_baseline.dpms_suspend);
    labeled_row(dpms_table, 2, "Suspend, s (0=off):", g_dpms_suspend_spin);
    g_dpms_off_spin = gtk_spin_button_new_with_range(0, 36000, 10);
    gtk_spin_button_set_value(GTK_SPIN_BUTTON(g_dpms_off_spin), g_power_baseline.dpms_off);
    labeled_row(dpms_table, 3, "Off, s (0=off):", g_dpms_off_spin);
    gtk_box_pack_start(GTK_BOX(outer), frame_with("DPMS", dpms_table), FALSE, FALSE, 0);

    GtkWidget *saver_table = gtk_table_new(3, 2, FALSE);
    g_saver_timeout_spin = gtk_spin_button_new_with_range(0, 36000, 10);
    gtk_spin_button_set_value(GTK_SPIN_BUTTON(g_saver_timeout_spin), g_power_baseline.saver_timeout);
    labeled_row(saver_table, 0, "Timeout, s (0=off):", g_saver_timeout_spin);
    g_saver_cycle_spin = gtk_spin_button_new_with_range(0, 36000, 10);
    gtk_spin_button_set_value(GTK_SPIN_BUTTON(g_saver_cycle_spin), g_power_baseline.saver_cycle);
    labeled_row(saver_table, 1, "Ciclo, s:", g_saver_cycle_spin);
    g_prefer_blank_chk = gtk_check_button_new_with_label(_("Preferir apagar a tela (blank)"));
    gtk_toggle_button_set_active(GTK_TOGGLE_BUTTON(g_prefer_blank_chk), g_power_baseline.prefer_blanking);
    gtk_table_attach(GTK_TABLE(saver_table), g_prefer_blank_chk, 0, 2, 2, 3, GTK_FILL, GTK_FILL, 4, 2);
    gtk_box_pack_start(GTK_BOX(outer), frame_with("Protetor de tela", saver_table), FALSE, FALSE, 0);

    GtkWidget *note = gtk_label_new(
        _("Fora do horario configurado, a tela volta a temperatura normal. "
          "Um horario de desligar menor que o de ligar cruza a meia-noite "
          "(ex.: ligar 20:00, desligar 06:00)."));
    gtk_misc_set_alignment(GTK_MISC(note), 0.0, 0.5);
    gtk_label_set_line_wrap(GTK_LABEL(note), TRUE);
    gtk_box_pack_start(GTK_BOX(outer), note, FALSE, FALSE, 0);

    GtkWidget *btnbox = gtk_hbox_new(FALSE, 0);
    GtkWidget *apply_btn = gtk_button_new_with_label(_("Aplicar"));
    g_signal_connect(apply_btn, "clicked", G_CALLBACK(apply_cb), NULL);
    gtk_box_pack_end(GTK_BOX(btnbox), apply_btn, FALSE, FALSE, 0);
    gtk_box_pack_start(GTK_BOX(outer), btnbox, FALSE, FALSE, 0);

    GtkWidget *scroll = gtk_scrolled_window_new(NULL, NULL);
    gtk_scrolled_window_set_policy(GTK_SCROLLED_WINDOW(scroll), GTK_POLICY_NEVER, GTK_POLICY_AUTOMATIC);
    gtk_scrolled_window_add_with_viewport(GTK_SCROLLED_WINDOW(scroll), outer);
    return scroll;
}
