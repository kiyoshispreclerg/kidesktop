/* kiconf - Bloqueio de tela tab: ~/.config/kilock.conf.
 *
 * i3lock has no config file, so the options live in kilock.conf and
 * `kilock` (what the session's xss-lock and the lock hotkey run) turns
 * them into i3lock arguments. The tab only exists when i3lock and kilock
 * are installed (lock_available()). The idle time before locking is
 * the screensaver timeout of the Energia tab, not set here. */
#include "../common.h"
#include "../tabs.h"

#include <limits.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "../../shared/xis_safefile.h"

typedef struct {
    char color[16];
    char image[PATH_MAX];
    int tiling, indicator, beep, ignore_empty, show_failed, pointer_default;
} Lock;

static GtkWidget *g_color_btn, *g_image_btn, *g_tiling_chk, *g_indicator_chk, *g_beep_chk;
static GtkWidget *g_empty_chk, *g_failed_chk, *g_pointer_chk, *g_status;

int lock_available(void)
{
    gchar *a = g_find_program_in_path("i3lock"), *b = g_find_program_in_path("kilock");
    int ok = a && b;
    g_free(a);
    g_free(b);
    return ok;
}

static void lock_defaults(Lock *l)
{
    memset(l, 0, sizeof(*l));
    snprintf(l->color, sizeof(l->color), "#ffffff"); /* i3lock's own default */
    l->indicator = 1;
}

static void lock_load(Lock *l)
{
    lock_defaults(l);
    char path[PATH_MAX];
    resolve_path("kilock.conf", path, sizeof(path));
    FILE *f = xis_fopen_read(path, xis_check_usable);
    if (!f)
        return;
    char line[PATH_MAX + 64];
    while (fgets(line, sizeof(line), f)) {
        char *s = trim(line);
        char *eq = strchr(s, '=');
        if (!*s || *s == '#' || !eq)
            continue;
        *eq = '\0';
        char *key = trim(s), *val = trim(eq + 1);
        if (!strcmp(key, "color")) {
            snprintf(l->color, sizeof(l->color), "%s%s", *val == '#' ? "" : "#", val);
        } else if (!strcmp(key, "image")) {
            snprintf(l->image, sizeof(l->image), "%s", val);
        } else if (!strcmp(key, "tiling")) {
            l->tiling = atoi(val) != 0;
        } else if (!strcmp(key, "indicator")) {
            l->indicator = atoi(val) != 0;
        } else if (!strcmp(key, "beep")) {
            l->beep = atoi(val) != 0;
        } else if (!strcmp(key, "ignore_empty")) {
            l->ignore_empty = atoi(val) != 0;
        } else if (!strcmp(key, "show_failed")) {
            l->show_failed = atoi(val) != 0;
        } else if (!strcmp(key, "pointer_default")) {
            l->pointer_default = atoi(val) != 0;
        }
    }
    fclose(f);
}

static int active(GtkWidget *chk)
{
    return gtk_toggle_button_get_active(GTK_TOGGLE_BUTTON(chk));
}

static void apply_cb(GtkWidget *w, gpointer data)
{
    (void)w;
    (void)data;
    char hex[16];
    color_button_hex(g_color_btn, hex, sizeof(hex));
    gchar *image = gtk_file_chooser_get_filename(GTK_FILE_CHOOSER(g_image_btn));

    char path[PATH_MAX], tmp[PATH_MAX + 8];
    resolve_path("kilock.conf", path, sizeof(path));
    snprintf(tmp, sizeof(tmp), "%s.tmp", path);
    FILE *f = xis_write_open(tmp, path);
    if (!f) {
        gtk_label_set_text(GTK_LABEL(g_status), _("Nao foi possivel salvar kilock.conf"));
        g_free(image);
        return;
    }
    fprintf(f, "# kilock config -- generated by kiconf's Bloqueio de tela tab.\n");
    fprintf(f, "color = %s\n", hex[0] == '#' ? hex + 1 : hex);
    fprintf(f, "image = %s\n", image ? image : "");
    fprintf(f, "tiling = %d\n", active(g_tiling_chk));
    fprintf(f, "indicator = %d\n", active(g_indicator_chk));
    fprintf(f, "beep = %d\n", active(g_beep_chk));
    fprintf(f, "ignore_empty = %d\n", active(g_empty_chk));
    fprintf(f, "show_failed = %d\n", active(g_failed_chk));
    fprintf(f, "pointer_default = %d\n", active(g_pointer_chk));
    g_free(image);
    if (xis_write_commit(f, tmp, path, xis_check_conf_clean) != 0) {
        gtk_label_set_text(GTK_LABEL(g_status), _("Nao foi possivel salvar kilock.conf"));
        return;
    }
    gtk_label_set_text(GTK_LABEL(g_status), _("Aplicado (vale no proximo bloqueio)"));
    kiconf_track_applied(g_status);
}

static void clear_image_cb(GtkWidget *w, gpointer data)
{
    (void)w;
    (void)data;
    gtk_file_chooser_unselect_all(GTK_FILE_CHOOSER(g_image_btn));
}

/* Locks for real: the screen comes back with the user's password. */
static void test_cb(GtkWidget *w, gpointer data)
{
    (void)w;
    (void)data;
    apply_cb(NULL, NULL);
    gchar *argv[] = {(gchar *)"kilock", NULL};
    GError *err = NULL;
    if (!g_spawn_async(NULL, argv, NULL, G_SPAWN_SEARCH_PATH, NULL, NULL, NULL, &err)) {
        gtk_label_set_text(GTK_LABEL(g_status), _("Nao foi possivel executar o kilock"));
        g_error_free(err);
    }
}

GtkWidget *build_lock_tab(void)
{
    Lock l;
    lock_load(&l);

    GtkWidget *outer = gtk_vbox_new(FALSE, 8);
    gtk_container_set_border_width(GTK_CONTAINER(outer), 12);

    GtkWidget *note = gtk_label_new(_("O bloqueio de tela usa o i3lock, que so aceita opcoes de linha de comando; "
                                      "aqui elas ficam guardadas em ~/.config/kilock.conf. O tempo parado ate "
                                      "bloquear e o do protetor de tela, na aba Energia."));
    gtk_misc_set_alignment(GTK_MISC(note), 0.0, 0.5);
    gtk_label_set_line_wrap(GTK_LABEL(note), TRUE);
    gtk_box_pack_start(GTK_BOX(outer), note, FALSE, FALSE, 0);

    GtkWidget *look = gtk_table_new(2, 2, FALSE);
    g_color_btn = labeled_row(look, 0, _("Cor de fundo:"), make_color_button(l.color));

    g_image_btn = gtk_file_chooser_button_new(_("Imagem de fundo"), GTK_FILE_CHOOSER_ACTION_OPEN);
    GtkFileFilter *png = gtk_file_filter_new();
    gtk_file_filter_set_name(png, "PNG");
    gtk_file_filter_add_mime_type(png, "image/png");
    gtk_file_chooser_add_filter(GTK_FILE_CHOOSER(g_image_btn), png);
    if (l.image[0])
        gtk_file_chooser_set_filename(GTK_FILE_CHOOSER(g_image_btn), l.image);
    gtk_widget_set_tooltip_text(g_image_btn, _("Somente PNG. Sem imagem, a tela fica com a cor de fundo."));
    GtkWidget *clear = gtk_button_new_with_label(_("Sem imagem"));
    g_signal_connect(clear, "clicked", G_CALLBACK(clear_image_cb), NULL);
    GtkWidget *img_row = gtk_hbox_new(FALSE, 6);
    gtk_box_pack_start(GTK_BOX(img_row), g_image_btn, TRUE, TRUE, 0);
    gtk_box_pack_start(GTK_BOX(img_row), clear, FALSE, FALSE, 0);
    labeled_row(look, 1, _("Imagem:"), img_row);
    gtk_box_pack_start(GTK_BOX(outer), frame_with(_("Aparencia"), look), FALSE, FALSE, 0);

    GtkWidget *opts = gtk_vbox_new(FALSE, 4);
    struct {
        GtkWidget **w;
        const char *label;
        int on;
    } rows[] = {
        {&g_tiling_chk, _("Repetir a imagem lado a lado"), l.tiling},
        {&g_indicator_chk, _("Mostrar o indicador de senha ao digitar"), l.indicator},
        {&g_failed_chk, _("Mostrar o numero de tentativas erradas"), l.show_failed},
        {&g_beep_chk, _("Apitar quando a senha estiver errada"), l.beep},
        {&g_empty_chk, _("Ignorar senha vazia (evita espera apos apertar Enter sem querer)"), l.ignore_empty},
        {&g_pointer_chk, _("Manter o ponteiro do mouse visivel"), l.pointer_default},
    };
    for (size_t i = 0; i < sizeof(rows) / sizeof(rows[0]); i++) {
        *rows[i].w = gtk_check_button_new_with_label(rows[i].label);
        gtk_toggle_button_set_active(GTK_TOGGLE_BUTTON(*rows[i].w), rows[i].on);
        gtk_box_pack_start(GTK_BOX(opts), *rows[i].w, FALSE, FALSE, 0);
    }
    gtk_box_pack_start(GTK_BOX(outer), frame_with(_("Comportamento"), opts), FALSE, FALSE, 0);

    GtkWidget *btns = gtk_hbox_new(FALSE, 6);
    g_status = gtk_label_new("");
    GtkWidget *apply = gtk_button_new_with_label(_("Aplicar"));
    g_signal_connect(apply, "clicked", G_CALLBACK(apply_cb), NULL);
    GtkWidget *test = gtk_button_new_with_label(_("Testar bloqueio"));
    gtk_widget_set_tooltip_text(test, _("Salva e bloqueia a tela agora; volte com a sua senha."));
    g_signal_connect(test, "clicked", G_CALLBACK(test_cb), NULL);
    gtk_box_pack_start(GTK_BOX(btns), g_status, FALSE, FALSE, 0);
    gtk_box_pack_end(GTK_BOX(btns), apply, FALSE, FALSE, 0);
    gtk_box_pack_end(GTK_BOX(btns), test, FALSE, FALSE, 0);
    gtk_box_pack_start(GTK_BOX(outer), btns, FALSE, FALSE, 0);
    return outer;
}
